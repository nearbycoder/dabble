#!/usr/bin/env bash
# Regenerates the copy of agent/skills/dabble/SKILL.md that the dabble CLI embeds,
# so `dabble skill install` works without the repo. Run after editing SKILL.md.
set -euo pipefail
cd "$(dirname "$0")/.."
out=Packages/DabbleKit/Sources/DabbleKit/Agent/AgentSkill.swift
{
  echo '// Generated by scripts/embed-skill.sh from agent/skills/dabble/SKILL.md. Do not edit.'
  echo
  echo 'public enum AgentSkill {'
  echo '    public static let name = "dabble"'
  echo '    public static let markdown = #"""'
  cat agent/skills/dabble/SKILL.md
  echo '"""#'
  echo '}'
} > "$out"
echo "Wrote $out"
